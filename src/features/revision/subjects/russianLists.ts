export const listCount = 5

export function themeAccepted(theme: Theme, topicId: string): ListExercise {
  return {
    kind: 'list',
    topicId,
    lang: 'ru',
    instruction: `Write ${listCount} different Russian words from this semantic field, as in the exam's language awareness question. Dictionary forms are best.`,
    theme: theme.theme,
    count: listCount,
    accepted: theme.accepted,
    note: `Words on this list: ${theme.accepted.slice(0, 12).join(', ')}…`,
  }
}
